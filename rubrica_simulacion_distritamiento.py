"""## 3. Generador Lineal Congruencial (GLC Mixto)"""

def generar_glc(xo, a, c, m):
    """
    Calcula el siguiente estado entero y el número pseudoaleatorio normalizado en [0, 1)
    mediante la relación: X_{i+1} = (a * X_i + c) % m
    """
    x_next = (a * xo + c) % m
    r = x_next / m
    return x_next, r

"""## 4. Lógica Geométrica (Rombo, Círculo y Distancias)"""

def es_punto_valido_zona_b(x, y, dx=DX, dy=DY, cx=CENTRO_X, cy=CENTRO_Y, radio_a=RADIO_ZONA_A):
    """
    Evalúa si el punto (x, y) cae dentro de la Zona B (rombo) y fuera de la Zona A (círculo).
    Utiliza las pendientes de los lados del rombo respecto a la línea horizontal media y = cy.
    """
    # 1. Excluir Zona A (círculo centrado en (cx, cy) con radio_a)[cite: 2, 5]
    dist_cuadrada_centro = (x - cx) ** 2 + (y - cy) ** 2
    if dist_cuadrada_centro <= radio_a ** 2:
        return False

    # 2. Verificar pertenencia al rombo mediante pendientes
    pendiente_base = dy / dx  # Ej. 6 / 8 = 0.75
    x_izq = cx - dx
    x_der = cx + dx

    if y >= cy:  # Mitad superior del rombo
        # Evitar división por cero si x coincide exactamente con el vértice izquierdo o derecho
        if x == x_izq:
            m_izq_ok = (y == cy)
        else:
            m_izq = (y - cy) / (x - x_izq)
            m_izq_ok = (m_izq <= pendiente_base) if (x > x_izq) else (m_izq >= pendiente_base)

        if x == x_der:
            m_der_ok = (y == cy)
        else:
            m_der = (y - cy) / (x - x_der)
            m_der_ok = (m_der >= -pendiente_base) if (x < x_der) else (m_der <= -pendiente_base)

        return m_izq_ok and m_der_ok
    else:  # Mitad inferior del rombo
        if x == x_izq:
            m_izq_ok = (y == cy)
        else:
            m_izq = (y - cy) / (x - x_izq)
            m_izq_ok = (m_izq >= -pendiente_base) if (x > x_izq) else (m_izq <= -pendiente_base)

        if x == x_der:
            m_der_ok = (y == cy)
        else:
            m_der = (y - cy) / (x - x_der)
            m_der_ok = (m_der <= pendiente_base) if (x < x_der) else (m_der >= pendiente_base)

        return m_izq_ok and m_der_ok


def calcular_distancias_metropolitanas(x, y, centros=CENTROS_DISTRIBUCION):
    """
    Calcula la distancia metropolitana (|x - xc| + |y - yc|)[cite: 3]
    desde el punto (x, y) hasta cada centro de distribución[cite: 5].
    """
    distancias = {}
    for nombre, (xc, yc) in centros.items():
        distancias[nombre] = abs(x - xc) + abs(y - yc)
    return distancias

"""## 5. Ejecución de la Simulación"""

def ejecutar_simulacion(
    n_iteraciones=N_ITERACIONES,
    xo_x=SEMILLA_X,
    xo_y=SEMILLA_Y,
    a=MULTIPLICADOR_A,
    c=CONSTANTE_C,
    m=MODULO_M,
    L=L_BASE,
    A=A_ALTURA,
):
    atenciones_centros = {nombre: 0 for nombre in CENTROS_DISTRIBUCION}
    distancias_totales = {nombre: 0.0 for nombre in CENTROS_DISTRIBUCION}

    puntos_validos_x, puntos_validos_y = [], []
    puntos_rechazados_x, puntos_rechazados_y = [], []
    centros_asignados = []

    validos = 0
    rechazados = 0

    for _ in range(n_iteraciones):
        xo_x, r1 = generar_glc(xo_x, a, c, m)
        xo_y, r2 = generar_glc(xo_y, a, c, m)

        # Escalamiento uniforme al intervalo [0, L] y [0, A][cite: 3]
        x = L * r1
        y = A * r2

        if es_punto_valido_zona_b(x, y):
            validos += 1
            puntos_validos_x.append(x)
            puntos_validos_y.append(y)

            distancias = calcular_distancias_metropolitanas(x, y)
            centro_ganador = min(distancias, key=distancias.get)

            atenciones_centros[centro_ganador] += 1
            distancias_totales[centro_ganador] += distancias[centro_ganador]
            centros_asignados.append(centro_ganador)
        else:
            rechazados += 1
            puntos_rechazados_x.append(x)
            puntos_rechazados_y.append(y)

    print("=" * 60)
    print(f"RESULTADOS DE LA SIMULACIÓN (N = {n_iteraciones}, m = {m})")
    print("=" * 60)
    print(f"Total posiciones generadas en rectángulo ({L} x {A} km): {n_iteraciones}")
    print(f"  - Válidos dentro de Zona B: {validos} ({(validos / n_iteraciones) * 100:.2f}%)")
    print(f"  - Rechazados (fuera rombo o en Zona A): {rechazados} ({(rechazados / n_iteraciones) * 100:.2f}%)\n")

    if validos > 0:
        for centro in CENTROS_DISTRIBUCION:
            porcentaje = (atenciones_centros[centro] / validos) * 100
            prom_dist = (
                distancias_totales[centro] / atenciones_centros[centro]
                if atenciones_centros[centro] > 0
                else 0.0
            )
            print(f"Centro {centro}:")
            print(f"  - Porcentaje de pedidos válidos atendidos: {porcentaje:.2f}%")
            print(f"  - Distancia promedio recorrida: {prom_dist:.2f} km\n")
    print("=" * 60)

    return (
        puntos_validos_x,
        puntos_validos_y,
        puntos_rechazados_x,
        puntos_rechazados_y,
        centros_asignados,
    )


x_vals, y_vals, x_rech, y_rech, asignaciones = ejecutar_simulacion()


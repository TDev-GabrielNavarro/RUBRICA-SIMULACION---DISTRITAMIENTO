MULTIPLICADOR_A = 21
CONSTANTE_C = 17
MODULO_M = 1000  # Mayor que N_ITERACIONES (1000)

# 3. Dimensiones y proporciones del modelo geométrico (en km)
# Basado en lado del rombo = 10 km[cite: 5] y terna pitagórica 6-8-10 (dx=8, dy=6)
